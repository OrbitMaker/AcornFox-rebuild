#!/usr/bin/env python3
"""重新生成 docs/licenses/licenses-manifest.json 与 THIRD_PARTY_NOTICES.md。

收录范围就是发布产物里实际带的第三方内容：
  - 编进 acornfox 的 Go 模块（各发布平台 go list -deps 的并集）与 Go 标准库；
  - 随发行版附带的 Caddy（版本取自 scripts/install/install.sh）；
  - 控制台与官网自带的 IBM Plex 字体（OFL.txt）。

用法：在仓库根目录执行 python3 scripts/gen-licenses.py
需要能执行 go，且模块已下载到本地缓存（go build 过即可）；Caddy 许可从 GitHub 读取。
"""

import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULE_DIR = os.path.join(ROOT, "acornfox")
OUT_DIR = os.path.join(ROOT, "docs", "licenses")
TARGETS = ["linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64", "windows/amd64", "windows/arm64"]
NOTICE_RE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([._-].*)?$", re.IGNORECASE)
FONT_DIRS = ["acornfox/internal/console/static/fonts", "website/assets/fonts"]
# IBM Plex 的上游版本，与 THIRD_PARTY_NOTICES 和字体目录的说明一致。
PLEX_VERSION = "IBM/plex@763c36e"


def go(*args, env=None):
    return subprocess.run(["go", *args], cwd=MODULE_DIR, env=env, check=True,
                          capture_output=True, text=True).stdout


def go_modules():
    """返回 {path: (version, dir)}，只含实际编进 acornfox 的第三方模块。"""
    mods = {}
    fmt = "{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}"
    for target in TARGETS:
        goos, goarch = target.split("/")
        env = dict(os.environ, GOOS=goos, GOARCH=goarch, CGO_ENABLED="0")
        for line in go("list", "-deps", "-f", fmt, "./cmd/acornfox", env=env).splitlines():
            parts = line.split("\t")
            if len(parts) != 3 or not parts[1]:
                continue  # 主模块没有版本
            mods[parts[0]] = (parts[1], parts[2])
    return mods


def notice_from_dir(path):
    """按旧清单的格式拼接：文件名一行，紧接全文；多个文件依次排列。"""
    names = sorted(n for n in os.listdir(path)
                   if NOTICE_RE.match(n) and os.path.isfile(os.path.join(path, n)))
    if not names:
        sys.exit(f"{path} 下找不到许可文件")
    parts = []
    for n in names:
        with open(os.path.join(path, n), encoding="utf-8") as f:
            text = f.read()
        parts.append(n + "\n" + (text if text.endswith("\n") else text + "\n"))
    return "".join(parts)


def component(name, version, source, notice):
    digest = hashlib.sha256(notice.encode("utf-8")).hexdigest()
    return {"name": name, "version": version, "license": "LicenseRef-" + digest,
            "source": source, "notice": notice, "notice_sha256": digest}


def caddy_version():
    with open(os.path.join(ROOT, "scripts", "install", "install.sh"), encoding="utf-8") as f:
        m = re.search(r'^\s*CADDY_VERSION="([0-9.]+)"$', f.read(), re.MULTILINE)
    if not m:
        sys.exit("无法从 install.sh 读取 CADDY_VERSION")
    return m.group(1)


def main():
    components = []
    for path, (version, mdir) in sorted(go_modules().items()):
        components.append(component("go:" + path, version,
                                    f"https://pkg.go.dev/{path}@{version}", notice_from_dir(mdir)))

    goversion = go("env", "GOVERSION").strip()
    goroot = go("env", "GOROOT").strip()
    with open(os.path.join(goroot, "LICENSE"), encoding="utf-8") as f:
        components.append(component("go:standard-library", goversion,
                                    f"https://go.dev/dl/#{goversion}", "LICENSE\n" + f.read()))

    cv = caddy_version()
    with urllib.request.urlopen(f"https://raw.githubusercontent.com/caddyserver/caddy/v{cv}/LICENSE", timeout=30) as r:
        caddy_license = r.read().decode("utf-8")
    components.append(component("bin:github.com/caddyserver/caddy/v2", "v" + cv,
                                f"https://github.com/caddyserver/caddy/releases/tag/v{cv}",
                                "LICENSE\n" + caddy_license))

    font_notices = set()
    for d in FONT_DIRS:
        with open(os.path.join(ROOT, d, "OFL.txt"), encoding="utf-8") as f:
            font_notices.add(f.read())
    if len(font_notices) != 1:
        sys.exit("控制台与官网的 OFL.txt 内容不一致")
    components.append(component("font:IBM Plex Sans / IBM Plex Mono", PLEX_VERSION,
                                "https://github.com/IBM/plex", "OFL.txt\n" + font_notices.pop()))

    manifest = {"schema_version": 1, "product": "acornfox", "license": "AGPL-3.0-only",
                "copyright": "Copyright (C) 2026 AcornFox contributors",
                "components": components}
    with open(os.path.join(OUT_DIR, "licenses-manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")

    lines = ["# Third-party notices", "",
             "Generated by `scripts/gen-licenses.py`. Complete, unmodified notice texts and their",
             "SHA-256 digests are in `licenses-manifest.json`.", "",
             "| Component | Version | Declared notice | Source |", "| --- | --- | --- | --- |"]
    for c in components:
        lines.append(f"| {c['name']} | {c['version']} | {c['license']} | {c['source']} |")
    lines += ["",
              "`go:` entries are compiled into the `acornfox` binary. `bin:` entries are shipped",
              "unmodified next to each release. The IBM Plex fonts (OFL-1.1, Reserved Font Name",
              "\"Plex\") are bundled in `" + FONT_DIRS[0] + "/` and `" + FONT_DIRS[1] + "/`,",
              "with the full license text in `OFL.txt` next to the font files.", ""]
    with open(os.path.join(OUT_DIR, "THIRD_PARTY_NOTICES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"已生成 {len(components)} 条组件记录")


if __name__ == "__main__":
    main()
